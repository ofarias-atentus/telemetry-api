package migrate

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
)

// schemaFacts son los datos del catálogo que identifican la versión del
// esquema creado por los scripts SQL antiguos.
type schemaFacts struct {
	Versioned          bool
	Devices            bool
	DeviceTelemetry    bool
	Hosts              bool
	Countries          bool
	TelemetryData      bool
	TelemetryBatteryPC bool
}

var errEmptyDatabase = errors.New("la base de datos está vacía: no hay esquema que registrar; usa `atelemetry-mobile migrate up`")

// detectVersion deduce la versión del esquema a partir de facts. Una base
// vacía o una combinación contradictoria devuelve error y no se cambia nada.
func detectVersion(f schemaFacts) (int64, error) {
	if !f.Devices && !f.DeviceTelemetry && !f.Hosts && !f.Countries {
		return 0, errEmptyDatabase
	}
	base := f.Devices && f.DeviceTelemetry
	oldMetrics := f.TelemetryBatteryPC && !f.TelemetryData
	newMetrics := f.TelemetryData && !f.TelemetryBatteryPC

	switch {
	case base && newMetrics && f.Hosts && f.Countries:
		return 4, nil
	case base && newMetrics && f.Hosts && !f.Countries:
		return 3, nil
	case base && newMetrics && !f.Hosts && !f.Countries:
		return 2, nil
	case base && oldMetrics && !f.Hosts && !f.Countries:
		return 1, nil
	}
	return 0, fmt.Errorf("el esquema no coincide con ninguna versión conocida "+
		"(devices=%t device_telemetry=%t hosts=%t countries=%t device_telemetry.data=%t device_telemetry.battery_pct=%t); "+
		"no se cambió nada",
		f.Devices, f.DeviceTelemetry, f.Hosts, f.Countries, f.TelemetryData, f.TelemetryBatteryPC)
}

func readFacts(ctx context.Context, q Querier) (schemaFacts, error) {
	var f schemaFacts
	err := q.QueryRow(ctx, `SELECT
		to_regclass('public.goose_db_version') IS NOT NULL,
		to_regclass('public.devices') IS NOT NULL,
		to_regclass('public.device_telemetry') IS NOT NULL,
		to_regclass('public.hosts') IS NOT NULL,
		to_regclass('public.countries') IS NOT NULL,
		EXISTS (SELECT 1 FROM information_schema.columns
			WHERE table_schema = 'public' AND table_name = 'device_telemetry' AND column_name = 'data'),
		EXISTS (SELECT 1 FROM information_schema.columns
			WHERE table_schema = 'public' AND table_name = 'device_telemetry' AND column_name = 'battery_pct')`).
		Scan(&f.Versioned, &f.Devices, &f.DeviceTelemetry, &f.Hosts, &f.Countries, &f.TelemetryData, &f.TelemetryBatteryPC)
	if err != nil {
		return schemaFacts{}, fmt.Errorf("no se pudo leer el catálogo de la base de datos: %w", err)
	}
	return f, nil
}

const createVersionsTableSQL = `CREATE TABLE goose_db_version (
	id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	version_id bigint NOT NULL,
	is_applied boolean NOT NULL,
	tstamp timestamp NOT NULL DEFAULT now()
)`

const insertVersionSQL = `INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, $2)`

// Baseline registra el historial de goose de una base creada con los scripts
// SQL antiguos: detecta su versión por el catálogo y crea goose_db_version con
// las filas 0..N en una sola transacción. Se niega si ya existe el historial.
// No cierra db.
func Baseline(ctx context.Context, db *sql.DB) (int64, error) {
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return 0, fmt.Errorf("no se pudo iniciar la transacción: %w", err)
	}
	defer func() { _ = tx.Rollback() }()

	// Serializa con migrate up (goose toma el mismo advisory lock).
	if _, err := tx.ExecContext(ctx, `SELECT pg_advisory_xact_lock($1)`, gooseLockKey); err != nil {
		return 0, fmt.Errorf("no se pudo tomar el bloqueo de migraciones: %w", err)
	}
	facts, err := readFacts(ctx, sqlQuerier{tx})
	if err != nil {
		return 0, err
	}
	if facts.Versioned {
		return 0, fmt.Errorf("%w: la base ya tiene historial de migraciones (%s); baseline solo sirve para bases sin historial",
			ErrVersionMismatch, VersionsTable)
	}
	version, err := detectVersion(facts)
	if err != nil {
		return 0, err
	}
	if _, err := tx.ExecContext(ctx, createVersionsTableSQL); err != nil {
		return 0, fmt.Errorf("no se pudo crear %s: %w", VersionsTable, err)
	}
	for v := int64(0); v <= version; v++ {
		if _, err := tx.ExecContext(ctx, insertVersionSQL, v, true); err != nil {
			return 0, fmt.Errorf("no se pudo registrar la versión %d: %w", v, err)
		}
	}
	if err := alignVersionsOwner(ctx, tx); err != nil {
		return 0, err
	}
	if err := tx.Commit(); err != nil {
		return 0, fmt.Errorf("no se pudo confirmar el baseline: %w", err)
	}
	return version, nil
}
